create table attempt (
    id bigint generated by default as identity primary key,
    lesson_id varchar(40) not null references lesson(id)
);

create table attempt_answer (
    attempt_id bigint not null references attempt(id),
    question_id bigint not null references question(id),
    selected_option varchar(1) not null check (selected_option in ('A', 'B', 'C')),
    correct boolean not null,
    primary key (attempt_id, question_id)
);

create index attempt_lesson_idx on attempt(lesson_id);
create index latest_answer_idx on attempt_answer(question_id, attempt_id desc);
